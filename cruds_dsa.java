    private void AddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddActionPerformed

      javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) PanelTable.getModel();

    String id = javax.swing.JOptionPane.showInputDialog(this, "Enter ID:");
    if (id == null || id.trim().isEmpty()) return;

    String name = javax.swing.JOptionPane.showInputDialog(this, "Enter Name:");
    if (name == null || name.trim().isEmpty()) return;

    String stock = javax.swing.JOptionPane.showInputDialog(this, "Enter Stock:");
    if (stock == null || stock.trim().isEmpty()) return;

    model.addRow(new Object[]{id, name, stock});

    javax.swing.JOptionPane.showMessageDialog(this, "Added successfully!");
      
    }//GEN-LAST:event_AddActionPerformed

    private void UpdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UpdActionPerformed
         int selectedRow = PanelTable.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please select a row to update.");
        return;
    }

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) PanelTable.getModel();

    String id = javax.swing.JOptionPane.showInputDialog(
            this, "Enter new ID:", model.getValueAt(selectedRow, 0));

    if (id == null || id.trim().isEmpty()) return;

    String name = javax.swing.JOptionPane.showInputDialog(
            this, "Enter new Name:", model.getValueAt(selectedRow, 1));

    if (name == null || name.trim().isEmpty()) return;

    String stock = javax.swing.JOptionPane.showInputDialog(
            this, "Enter new Stock:", model.getValueAt(selectedRow, 2));

    if (stock == null || stock.trim().isEmpty()) return;

    model.setValueAt(id, selectedRow, 0);
    model.setValueAt(name, selectedRow, 1);
    model.setValueAt(stock, selectedRow, 2);

    javax.swing.JOptionPane.showMessageDialog(this,
            "Updated successfully!");
    }//GEN-LAST:event_UpdActionPerformed

    private void DelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DelActionPerformed
         int selectedRow = PanelTable.getSelectedRow();

    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Please select a row to delete.");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this record?",
            "Confirm Delete",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirm == javax.swing.JOptionPane.YES_OPTION) {

        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) PanelTable.getModel();

        model.removeRow(selectedRow);

        javax.swing.JOptionPane.showMessageDialog(this,
                "Deleted successfully!");
    }
    }//GEN-LAST:event_DelActionPerformed

